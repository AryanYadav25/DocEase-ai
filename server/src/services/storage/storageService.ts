import { createHash, randomUUID } from 'node:crypto';
import { createReadStream } from 'node:fs';
import fs from 'node:fs/promises';
import path from 'node:path';
import { env } from '../../config/env.js';
import { logger } from '../../config/logger.js';

/**
 * Storage adapter. The only driver shipped is the local filesystem, kept outside any
 * static directory. An S3/GCS driver can implement the same interface.
 */
export interface StorageDriver {
  save(ownerId: string, sourcePath: string, ext: string): Promise<{ key: string }>;
  resolve(key: string): string;
  remove(key: string): Promise<void>;
  exists(key: string): Promise<boolean>;
  createReadStream(key: string): NodeJS.ReadableStream;
}

const STORAGE_ROOT = path.resolve(process.cwd(), env.STORAGE_DIR);
export const TMP_ROOT = path.resolve(process.cwd(), env.TMP_DIR);

export async function ensureStorageDirs() {
  await fs.mkdir(path.join(STORAGE_ROOT, 'documents'), { recursive: true });
  await fs.mkdir(TMP_ROOT, { recursive: true });
}

const SAFE_KEY = /^documents\/[a-f\d]{24}\/[a-f\d-]{36}\.(pdf|png|jpg|webp|txt|docx)$/;

/** Prevent path traversal: keys are generated by us and must match the strict pattern. */
function assertSafeKey(key: string) {
  if (!SAFE_KEY.test(key)) throw new Error('Unsafe storage key');
  const resolved = path.resolve(STORAGE_ROOT, key);
  if (!resolved.startsWith(STORAGE_ROOT + path.sep)) throw new Error('Unsafe storage key');
  return resolved;
}

export const localStorageDriver: StorageDriver = {
  async save(ownerId, sourcePath, ext) {
    const key = `documents/${ownerId}/${randomUUID()}.${ext}`;
    const dest = assertSafeKey(key);
    await fs.mkdir(path.dirname(dest), { recursive: true });
    try {
      await fs.rename(sourcePath, dest);
    } catch {
      await fs.copyFile(sourcePath, dest);
      await fs.unlink(sourcePath).catch(() => undefined);
    }
    return { key };
  },
  resolve(key) {
    return assertSafeKey(key);
  },
  async remove(key) {
    const p = assertSafeKey(key);
    await fs.unlink(p).catch((err: NodeJS.ErrnoException) => {
      if (err.code !== 'ENOENT') logger.warn({ err, key }, 'Failed to remove stored file');
    });
  },
  async exists(key) {
    try {
      await fs.access(assertSafeKey(key));
      return true;
    } catch {
      return false;
    }
  },
  createReadStream(key) {
    return createReadStream(assertSafeKey(key));
  },
};

export const storage: StorageDriver = localStorageDriver;

export async function hashFile(filePath: string): Promise<string> {
  const hash = createHash('sha256');
  const stream = createReadStream(filePath);
  for await (const chunk of stream) hash.update(chunk as Buffer);
  return hash.digest('hex');
}

export async function removeTempFile(filePath: string | undefined) {
  if (!filePath) return;
  await fs.unlink(filePath).catch(() => undefined);
}

/** Sanitise a user-supplied filename for display/storage in the DB (never used as a path). */
export function sanitizeFilename(name: string): string {
  const base = path.basename(name).replace(/[\u0000-\u001f\u007f<>:"/\\|?*]+/g, '_').trim();
  return (base || 'document').slice(0, 255);
}
